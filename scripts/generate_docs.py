def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated pages differ; write no files.')
    args = parser.parse_args()
    changed = []
    for name, text in build().items():
        path = ROOT / name
        existing = path.read_text(encoding='utf-8') if path.exists() else None
        if existing != text:
            changed.append(name)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding='utf-8')
    if args.check and changed:
        raise SystemExit('Generated content is stale:\n' + '\n'.join(changed))
    print(f'Generated content {"checked" if args.check else "updated"}: {len(changed)} changed files.')


if __name__ == '__main__':
    main()
